import {readFileSync} from 'node:fs';

export const manifestPath=new URL('../config/release-manifest.json',import.meta.url);
export const manifest=JSON.parse(readFileSync(manifestPath,'utf8'));

export function renderReleaseReference(value=manifest){
  const deploymentRows=Object.values(value.deployments).map(item=>`| ${item.label} | ${item.status} | ${item.frontendUrl} | ${item.apiUrl} | \`${item.wranglerConfig}\` | ${item.liveProviders?'Live providers controlled by API':'Deterministic only'} |`).join('\n');
  const systemRows=value.systems.map(item=>`| ${item.capability} | ${item.provider} \`${item.modelIdentifier}\` | ${item.purpose} | ${item.authority} | ${item.fallbackBehavior} |`).join('\n');
  const stateRows=Object.entries(value.executionStates).map(([name,meaning])=>`| ${name} | ${meaning} |`).join('\n');
  const vocabularyRows=Object.entries(value.vocabulary).map(([name,meaning])=>`| ${name} | ${meaning} |`).join('\n');
  return `# Authoritative Minsk release reference

This file is generated from \`config/release-manifest.json\`. Change the manifest, then run \`pnpm release:sync\`; do not edit this file directly.

## Deployments

| Environment | Status | Frontend | API | Configuration | Provider mode |
| --- | --- | --- | --- | --- | --- |
${deploymentRows}

Only **Judge production** is the canonical judge URL. The release-candidate alias is a pre-promotion verification target. Historical deterministic-review names are retained solely as provenance for old evidence and are not current release endpoints.

## Model-purpose matrix

| Capability | System | Purpose | Authority | Fallback behaviour |
| --- | --- | --- | --- | --- |
${systemRows}

The configuration source for every entry is recorded in the manifest. A routed challenger or investigation model is a server-side system choice, not a model manually selected by the judge.

## Execution states

| State | Meaning |
| --- | --- |
${stateRows}

## Vocabulary

| Term | Authoritative meaning |
| --- | --- |
${vocabularyRows}
`;
}
